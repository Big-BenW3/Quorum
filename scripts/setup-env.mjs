#!/usr/bin/env node
/** Creates .env.local with freshly generated secrets for local development. Never overwrites. */
import { randomBytes } from "node:crypto";
import { existsSync, writeFileSync } from "node:fs";

if (existsSync(".env.local")) { console.log(".env.local already exists — leaving it untouched."); process.exit(0); }
const secret = (n) => randomBytes(n).toString("base64url");
writeFileSync(".env.local", `# Generated by \`npm run setup\`. Local development only. Never commit this file.
APP_URL="http://localhost:3000"
DATABASE_URL="file:./.data/dev.db"
BETTER_AUTH_SECRET="${secret(32)}"
APP_SECRET="${secret(48)}"
CRON_SECRET="${secret(24)}"
MAIL_DRIVER="console"
STORAGE_DRIVER="local"
RATE_LIMIT_DRIVER="database"
JOB_DRIVER="inline"
OCR_DRIVER="none"
`, { mode: 0o600 });
console.log("Wrote .env.local (mode 600). Next: npm run db:migrate && npm run dev");
